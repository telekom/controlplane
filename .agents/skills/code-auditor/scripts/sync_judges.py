"""Generate the harness agent definitions from the pinned judges.

The pin lives in ``.agents/judges.yaml`` and is recorded in every receipt. The
model that actually answers is chosen by the harness, from its own agent
directory. Two sources of truth for one fact is exactly the shape of a silent
lie: a subagent definition without a ``model`` inherits the session's model, so
a receipt can name Haiku while Opus did the work, and nothing errors.

So the agent files are generated, never written by hand, and ``--check``
refuses a commit where they have drifted from the pin.

Usage::

    sync_judges.py              # write the agent definitions
    sync_judges.py --check      # fail if they are not current
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from auditlib import changeset  # noqa: E402
from auditlib.judges import Judge, JudgeError, load as load_judges  # noqa: E402
from auditlib.yamlish import YamlishError, split_frontmatter  # noqa: E402

PERSONA = Path(__file__).resolve().parent.parent / "persona" / "README.md"
GENERATED = (
    "<!-- Generated by .agents/skills/code-auditor/scripts/sync_judges.py. "
    "Edit .agents/judges.yaml or the persona instead. -->"
)
DESCRIPTION = (
    "Answers one code-auditor work unit against one rule, using only the "
    "frozen context in the prompt"
)


def _opencode(judge: Judge, body: str) -> str:
    return (
        "---\n"
        f"description: {DESCRIPTION} ({judge.tier} judge)\n"
        "mode: subagent\n"
        f"model: {judge.pin}\n"
        "permissions:\n"
        '  - action: "*"\n'
        '    resource: "*"\n'
        "    effect: deny\n"
        "  - action: shell\n"
        '    resource: "*show_work_unit.py*"\n'
        "    effect: allow\n"
        "---\n"
        f"\n{GENERATED}\n\n{body}\n"
    )


def _claude(judge: Judge, body: str) -> str:
    provider, _, model = judge.model.partition("/")
    if provider != "anthropic":
        raise JudgeError(
            f"judge '{judge.tier}' is pinned to {judge.model}, which Claude Code "
            f"cannot run; it accepts Anthropic model ids only"
        )
    effort = f"effort: {judge.effort}\n" if judge.effort else ""
    return (
        "---\n"
        f"name: audit-judge-{judge.tier}\n"
        f"description: {DESCRIPTION} ({judge.tier} judge)\n"
        f"model: {model}\n"
        f"{effort}"
        "tools: Bash\n"
        "omitClaudeMd: true\n"
        "---\n"
        f"\n{GENERATED}\n\n{body}\n"
    )


def targets(root: Path, judge: Judge, body: str) -> dict[Path, str]:
    name = f"audit-judge-{judge.tier}.md"
    return {
        root / ".opencode" / "agents" / name: _opencode(judge, body),
        root / ".claude" / "agents" / name: _claude(judge, body),
    }


def persona_body() -> str:
    try:
        _, body = split_frontmatter(PERSONA.read_text(encoding="utf-8"))
    except (OSError, YamlishError) as exc:
        raise JudgeError(f"{PERSONA}: {exc}") from exc
    body = body.strip()
    if not body:
        raise JudgeError(f"{PERSONA}: the persona has no body")
    return body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="verify instead of writing"
    )
    parser.add_argument("paths", nargs="*", help="ignored; accepted for pre-commit")
    args = parser.parse_args()

    root = changeset.repo_root()
    try:
        judges = load_judges(root)
        body = persona_body()
        wanted: dict[Path, str] = {}
        for tier in judges.tiers:
            wanted |= targets(root, judges.get(tier), body)
    except JudgeError as exc:
        print(f"sync-judges: {exc}", file=sys.stderr)
        return 2

    stale = [
        path
        for path, content in wanted.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]

    if args.check:
        if stale:
            print(
                "sync-judges: the harness judges no longer match "
                f"{judges.default!r} and the other pins in .agents/judges.yaml:",
                file=sys.stderr,
            )
            for path in stale:
                print(f"  - {path.relative_to(root)}", file=sys.stderr)
            print(
                "Run: python3 .agents/skills/code-auditor/scripts/sync_judges.py",
                file=sys.stderr,
            )
            return 1
        print(f"sync-judges: {len(wanted)} agent definition(s) match the pins.")
        return 0

    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(wanted[path], encoding="utf-8")
        print(f"sync-judges: wrote {path.relative_to(root)}")
    if not stale:
        print(f"sync-judges: {len(wanted)} agent definition(s) already current.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
