"""Generate the architecture-reviewer agent for every harness from one source.

The persona lives in ``reviewer/README.md``. Each harness reads its own agent
directory with its own frontmatter, so the files are generated, never edited
by hand, and ``--check`` refuses a commit where one has drifted.

- VS Code GitHub Copilot: ``.github/agents/architecture-reviewer.agent.md``
- OpenCode: ``.opencode/agents/architecture-reviewer.md``
- Claude Code: ``.claude/agents/architecture-reviewer.md``

No model is pinned: the reviewer orients, it does not produce verdicts that
are cached or receipted, so it runs on whatever the caller's harness chooses.

Usage::

    sync_reviewer.py              # write the agent definitions
    sync_reviewer.py --check      # fail if they are not current
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SKILL.parent / "code-auditor" / "scripts"))

from auditlib import changeset  # noqa: E402
from auditlib.yamlish import YamlishError, split_frontmatter  # noqa: E402

NAME = "architecture-reviewer"
PERSONA = SKILL / "reviewer" / "README.md"
GENERATED = (
    "<!-- Generated by .agents/skills/review-architecture/scripts/sync_reviewer.py. "
    "Edit .agents/skills/review-architecture/reviewer/README.md instead. -->"
)
DESCRIPTION = (
    "Read-only architecture guide for the Controlplane repository. Use for an "
    "architecture overview of a change, plan or question: the domains and layers "
    "involved, the ADRs that apply, the invariants at risk, and what to read next."
)


def _copilot(body: str) -> str:
    return (
        "---\n"
        f"name: {NAME}\n"
        f'description: "{DESCRIPTION}"\n'
        "target: github-copilot\n"
        "tools: ['read', 'search', 'execute']\n"
        "---\n"
        f"\n{GENERATED}\n\n{body}\n"
    )


def _opencode(body: str) -> str:
    return (
        "---\n"
        f'description: "{DESCRIPTION}"\n'
        "mode: subagent\n"
        "permission:\n"
        "  edit: deny\n"
        "  task: deny\n"
        "  webfetch: deny\n"
        "---\n"
        f"\n{GENERATED}\n\n{body}\n"
    )


def _claude(body: str) -> str:
    return (
        "---\n"
        f"name: {NAME}\n"
        f'description: "{DESCRIPTION}"\n'
        "tools: Read, Grep, Glob, Bash\n"
        "---\n"
        f"\n{GENERATED}\n\n{body}\n"
    )


def targets(root: Path, body: str) -> dict[Path, str]:
    return {
        root / ".github" / "agents" / f"{NAME}.agent.md": _copilot(body),
        root / ".opencode" / "agents" / f"{NAME}.md": _opencode(body),
        root / ".claude" / "agents" / f"{NAME}.md": _claude(body),
    }


def persona_body(path: Path = PERSONA) -> str:
    try:
        _, body = split_frontmatter(path.read_text(encoding="utf-8"))
    except (OSError, YamlishError) as exc:
        raise SystemExit(f"sync-reviewer: {path}: {exc}") from exc
    body = body.strip()
    if not body:
        raise SystemExit(f"sync-reviewer: {path}: the persona has no body")
    return body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    parser.add_argument("--root", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("paths", nargs="*", help="ignored; accepted for pre-commit")
    args = parser.parse_args(argv)

    root = args.root or changeset.repo_root()
    wanted = targets(root, persona_body())
    stale = [
        path
        for path, content in wanted.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]

    if args.check:
        if stale:
            print("sync-reviewer: the architecture-reviewer agents are out of date:", file=sys.stderr)
            for path in stale:
                print(f"  - {path.relative_to(root)}", file=sys.stderr)
            print(
                "Run: python3 .agents/skills/review-architecture/scripts/sync_reviewer.py",
                file=sys.stderr,
            )
            return 1
        print(f"sync-reviewer: {len(wanted)} agent definition(s) match the persona.")
        return 0

    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(wanted[path], encoding="utf-8")
        print(f"sync-reviewer: wrote {path.relative_to(root)}")
    if not stale:
        print(f"sync-reviewer: {len(wanted)} agent definition(s) already current.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
